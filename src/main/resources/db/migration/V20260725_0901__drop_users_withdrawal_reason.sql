-- 회원 탈퇴 사유(withdrawal_reason) 컬럼 제거 (#115)
--
-- 배경: 탈퇴 사유는 자유 입력이라 개인정보가 포함될 수 있어 원문을 저장하지 않았고,
--   코드에서는 항상 null만 기록해 온 사실상 죽은 컬럼이었다. 탈퇴 사유 입력 자체를
--   폐지하면서 엔티티 매핑을 제거했고, 이에 맞춰 컬럼도 정리한다.
--
-- 배포 순서(중요): 이 마이그레이션은 신규 앱 기동 시 Flyway가 실행하며 컬럼을 제거한다.
--   구버전 앱(이 컬럼을 매핑하던 #115 이전 이미지)이 컬럼 제거 후에도 살아 있으면 User
--   조회/저장에서 "Unknown column 'withdrawal_reason'" 오류가 난다. 따라서
--   (1) 구버전 컨테이너를 먼저 종료(drain)한 뒤 신규 버전을 기동하고,
--   (2) 이 마이그레이션 적용 이후에는 #115 이전 이미지로 롤백하지 않는다
--       (롤백이 필요하면 컬럼을 되살리는 별도 마이그레이션을 선행해야 한다).
--   단일 인스턴스 stop→start 배포에서는 두 버전이 동시에 뜨지 않아 안전하다.
ALTER TABLE users DROP COLUMN withdrawal_reason;
